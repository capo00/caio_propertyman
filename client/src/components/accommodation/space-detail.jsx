import { createVisualComponent, Lsi, useLanguage } from "uu5g05";
import Uu5Elements from "uu5g05-elements";
import Config from "../../config/config.js";
import Section from "../section.jsx";
import Eyebrow from "../eyebrow.jsx";
import Heading from "../heading.jsx";
import Button from "../button.jsx";
import Photo from "../photo.jsx";
import GalleryGrid from "../gallery-grid.jsx";
import AmenityCard from "./amenity-card.jsx";
import NotFound from "../not-found.jsx";
import spaces from "./content.js";
import amenities from "./amenities.js";
import { getSpacePhotos } from "../../tools/space-photos.js";
import { lsi } from "../../lsi/import-lsi.js";
import { pagePath } from "../../tools/page-language.js";
import { pluralForm } from "../../tools/plural.js";

const { theme } = Config;

// Space detail: /ubytovani/<code>. One template for all spaces -- if each were
// assembled by hand, they would drift apart the first time another one is added.
//
// Routes here are generated by router.jsx from the same list the space is read from here, so
// a `code` that does not exist has no way to arrive here. The 404 safeguard is therefore for the case
// where a space is removed from the list but a link to it remains somewhere.
//
// The lightbox has its own group for each space (`space-<code>`) -- with a shared group
// "roubenka" the arrows in the lightbox would also lead to photos that are not on this page at all.

/** Neighbours in the order of spaces -- the "previous/next" links at the end of the page. */
function getNeighbours(list, index) {
  return { prev: list[index - 1] ?? null, next: list[index + 1] ?? null };
}

const SpaceDetail = createVisualComponent({
  uu5Tag: Config.TAG + "SpaceDetail",

  render({ code }) {
    const [language] = useLanguage();
    const list = [...spaces].sort((a, b) => a.order - b.order);
    const index = list.findIndex((item) => item.code === code);
    const space = list[index];

    if (!space) return <NotFound />;

    const photos = getSpacePhotos(space);
    const spaceAmenities = [...amenities]
      .filter((item) => space.amenityCodes?.includes(item.code))
      .sort((a, b) => a.order - b.order);
    const units = [...(space.units ?? [])].sort((a, b) => a.order - b.order);
    const { prev, next } = getNeighbours(list, index);

    return (
      <>
        <Section id={`prostor-${space.code}`}>
          <Eyebrow lsi={lsi("pages", "space", "eyebrow")} />
          <Heading level={1} lsi={lsi("spaces", space.code, "title")} />
          <p
            className={Config.Css.css({
              ...theme.text.body,
              color: theme.color.mutedFg,
              marginBlock: "16px 28px",
              maxWidth: 680,
              whiteSpace: "pre-line",
            })}
          >
            <Lsi lsi={lsi("spaces", space.code, "perex")} />
          </p>

          {photos.length > 0 ? (
            <GalleryGrid items={photos} lightbox={`space-${space.code}`} minColumnSize={280} />
          ) : (
            // Until the space has photos, a toned area holds the composition -- so it is visible
            // that photos are still to come here, instead of an empty spot. The width is limited to the width
            // of the text column: across the whole page the placeholder becomes a band that overpowers
            // even the heading, and that is too much for unfinished content.
            <div className={Config.Css.css({ maxWidth: 680 })}>
              <Photo
                src={null}
                tone={space.placeholderTone}
                ratio="16 / 9"
                caption={lsi("spaces", space.code, "title")}
              />
            </div>
          )}

          <p
            className={Config.Css.css({
              ...theme.text.body,
              color: theme.color.fg,
              marginBlock: "32px 0",
              maxWidth: 680,
              whiteSpace: "pre-line",
            })}
          >
            <Lsi lsi={lsi("spaces", space.code, "description")} />
          </p>
        </Section>

        {units.length > 0 && (
          <Section variant="cream">
            <Heading level={2} lsi={lsi("pages", "space", "unitsHeading")} />

            <Uu5Elements.Grid
              templateColumns="repeat(auto-fit, minmax(260px, 1fr))"
              rowGap={16}
              columnGap={16}
              className={Config.Css.css({ marginBlockStart: 28 })}
            >
              {units.map((unit) => (
                <Uu5Elements.Tile
                  key={unit.code}
                  colorScheme="building"
                  significance="subdued"
                  borderRadius="moderate"
                  header={
                    <Uu5Elements.Grid templateColumns="1fr auto" columnGap={12} alignItems="baseline">
                      <Heading level={3} lsi={lsi("spaces", space.code, "units", unit.code, "title")} />
                      {/* Number of beds as "2 lůžka" / "5 lůžek": uu5g05 LSI has no plurals,
                          so the form comes from `pluralForm` (Intl.PluralRules), the same as
                          the nights in the booking form. */}
                      <span
                        className={Config.Css.css({
                          ...theme.text.eyebrow,
                          color: theme.color.accent,
                          whiteSpace: "nowrap",
                        })}
                      >
                        <Uu5Elements.Number value={unit.beds} />{" "}
                        <Lsi lsi={lsi("pages", "space", "beds", pluralForm(unit.beds, language))} />
                      </span>
                    </Uu5Elements.Grid>
                  }
                >
                  <p
                    className={Config.Css.css({
                      ...theme.text.small,
                      color: theme.color.mutedFg,
                      margin: 0,
                      whiteSpace: "pre-line",
                    })}
                  >
                    <Lsi lsi={lsi("spaces", space.code, "units", unit.code, "description")} />
                  </p>
                </Uu5Elements.Tile>
              ))}
            </Uu5Elements.Grid>
          </Section>
        )}

        {spaceAmenities.length > 0 && (
          <Section>
            <Heading level={2} lsi={lsi("pages", "space", "amenitiesHeading")} />

            <Uu5Elements.Grid
              templateColumns="repeat(auto-fit, minmax(260px, 1fr))"
              rowGap={16}
              columnGap={16}
              className={Config.Css.css({ marginBlockStart: 28 })}
            >
              {spaceAmenities.map((amenity) => (
                <AmenityCard key={amenity.code} amenity={amenity} />
              ))}
            </Uu5Elements.Grid>
          </Section>
        )}

        <Section variant="cream">
          <Uu5Elements.Grid
            templateColumns={{ xs: "1fr", m: "1fr auto 1fr" }}
            columnGap={16}
            rowGap={12}
            alignItems="center"
          >
            {/* The empty cells keep the middle button centred even for the first and last spaces. */}
            <div>
              {prev && (
                <Uu5Elements.Link href={pagePath("accommodation", { space: prev.code })} colorScheme="primary" underline="onHover">
                  ← <Lsi lsi={lsi("spaces", prev.code, "title")} />
                </Uu5Elements.Link>
              )}
            </div>

            <Button variant="outline" href={pagePath("accommodation")} lsi={lsi("pages", "space", "backButton")} />

            <div className={Config.Css.css({ textAlign: "right" })}>
              {next && (
                <Uu5Elements.Link href={pagePath("accommodation", { space: next.code })} colorScheme="primary" underline="onHover">
                  <Lsi lsi={lsi("spaces", next.code, "title")} /> →
                </Uu5Elements.Link>
              )}
            </div>
          </Uu5Elements.Grid>
        </Section>
      </>
    );
  },
});

export default SpaceDetail;
